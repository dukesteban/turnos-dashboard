-- ============================================================
-- ingresos (ventas sueltas que NO son turnos)
-- ------------------------------------------------------------
-- Una venta que no se agendo: el shampoo que sale del stock, el
-- trabajo a domicilio que no quedo en la Agenda.
--
-- Hoy esa plata NO existe: la Caja solo suma turnos atendidos
-- (`getGanancias`). Por eso ni "Ganancias por dia" ni el cuadro
-- de Ingresos cuadran con la caja fisica.
--
-- Tabla propia y NO `compras_proveedor` con signo invertido: meter
-- entradas en la tabla de gastos ensucia el calculo de Gastos.
--
-- Sin empleado y sin comision a proposito: es un ingreso del local,
-- no de una persona. Si manana el jefe quiere comisionar una venta
-- suelta, se agrega un `empleado_id` y se clasifica aparte en el
-- detalle de comisiones; por ahora el boton queda simple.
--
-- Permisos: mismos roles que `pagos_empleado` con escritura
-- ampliada a secretario, porque el ingreso lo carga quien esta
-- en la caja, que puede ser el secretario.
-- ============================================================

CREATE TABLE public.ingresos (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha date NOT NULL,
    concepto text,
    monto numeric(12,2) NOT NULL,
    metodo_pago text,
    notas text,
    created_at timestamp with time zone DEFAULT now(),
    CONSTRAINT ingresos_monto_check CHECK ((monto > (0)::numeric))
);

COMMENT ON TABLE public.ingresos IS 'Ingresos de Caja que NO son turnos: ventas sueltas, trabajos sin agenda. Suman al cuadro de Ingresos, a Ganancias por dia y a Por metodo de pago.';

ALTER TABLE public.ingresos ENABLE ROW LEVEL SECURITY;

CREATE POLICY ingresos_leer ON public.ingresos FOR SELECT TO authenticated
  USING ((public.rol_actual() = ANY (ARRAY['admin'::text, 'secretario'::text])));

CREATE POLICY ingresos_crear ON public.ingresos FOR INSERT TO authenticated
  WITH CHECK ((public.rol_actual() = ANY (ARRAY['admin'::text, 'secretario'::text])));

CREATE POLICY ingresos_editar ON public.ingresos FOR UPDATE TO authenticated
  USING ((public.rol_actual() = ANY (ARRAY['admin'::text, 'secretario'::text])))
  WITH CHECK ((public.rol_actual() = ANY (ARRAY['admin'::text, 'secretario'::text])));

CREATE POLICY ingresos_borrar ON public.ingresos FOR DELETE TO authenticated
  USING ((public.rol_actual() = ANY (ARRAY['admin'::text, 'secretario'::text])));
